// Writes src/styles/theme.css from the color tokens in src/theme/colors.ts,
// so Uniwind class names (bg-primary, text-on-surface, ...) and the beUI
// Native components use the same colors as the TypeScript tokens.
//
//   npm run tokens          Write the file
//   npm run tokens:check    Fail if the file is out of date (used in CI)
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const { lightColors, darkColors } = await import('../src/theme/colors.ts');
const out = fileURLToPath(new URL('../src/styles/theme.css', import.meta.url));

const kebab = (name) => name.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);

// beUI Native components use these names. Map them onto our M3 roles.
const beuiAliases = {
  // background, primary, on-primary and surface already match by name.
  foreground: 'onSurface',
  muted: 'onSurfaceVariant',
  border: 'outlineVariant',
  'border-strong': 'outline',
  destructive: 'error',
};

function block(variant, colors) {
  const lines = Object.entries(colors).map(([k, v]) => `      --color-${kebab(k)}: ${v};`);
  for (const [alias, role] of Object.entries(beuiAliases)) {
    lines.push(`      --color-${alias}: ${colors[role]}; /* beUI alias of ${kebab(role)} */`);
  }
  return `  :root {\n    @variant ${variant} {\n${lines.join('\n')}\n    }\n  }`;
}

const css = `/* GENERATED by scripts/build-theme-css.mjs from src/theme/colors.ts.
   Do not edit by hand: change colors.ts and run \`npm run tokens\`. */
@layer theme {
${block('light', lightColors)}

${block('dark', darkColors)}

  /* Tailwind's default monospace stack isn't a font React Native can load. */
  :root {
    @variant ios {
      --font-mono: Menlo;
    }
  }

  :root {
    @variant android {
      --font-mono: monospace;
    }
  }
}
`;

if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(out, 'utf8');
  } catch {}
  if (current !== css) {
    console.error('src/styles/theme.css is out of date. Run `npm run tokens`.');
    process.exit(1);
  }
  console.log('src/styles/theme.css is up to date.');
} else {
  writeFileSync(out, css);
  console.log('Wrote src/styles/theme.css');
}
